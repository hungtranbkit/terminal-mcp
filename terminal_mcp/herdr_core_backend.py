"""SessionBackend implementation for herdr-core's verified ``hc`` CLI.

The contract is generated by herdr-core 0.1.18 (OpenRPC protocol 1).  Every
call uses JSON, a fixed argv list, no shell, and a bounded timeout.  tmux
remains the default; selecting this backend is an explicit factory decision.
"""
from __future__ import annotations

import json
import os
import subprocess
from dataclasses import dataclass
from typing import Any, Callable

from .models import SessionInfo
from .tmux import TmuxError


class HerdrCoreError(TmuxError):
    def __init__(self, code: str, detail: str = "") -> None:
        self.code = code
        self.detail = detail
        super().__init__(code if not detail else f"{code}: {detail}")


Runner = Callable[..., subprocess.CompletedProcess[str]]


def _run(argv: list[str], **kwargs: Any) -> subprocess.CompletedProcess[str]:
    return subprocess.run(argv, **kwargs)


@dataclass(frozen=True)
class HerdrCapabilities:
    create: bool = True
    read: bool = True
    send: bool = True
    keys: bool = True
    attach: bool = True
    detach: bool = False
    terminate: bool = True
    osc_7501: bool = True


class HerdrCoreBackend:
    """Adapt hc terminal operations to TerminalService's existing backend."""

    ansi_capture_supported = False

    def __init__(self, binary: str = "hc", *, timeout_seconds: float = 5.0,
                 runner: Runner = _run, session: str | None = None) -> None:
        self.binary = os.path.expanduser(binary)
        self.timeout_seconds = max(0.1, min(float(timeout_seconds), 30.0))
        self.runner = runner
        self.session = session
        self.capabilities = HerdrCapabilities()

    def _env(self) -> dict[str, str]:
        env = os.environ.copy()
        for key in ("HC_TERMINAL_ID", "HC_MACHINE"):
            env.pop(key, None)
        if self.session:
            env["HC_SESSION"] = self.session
        return env

    def _call(self, *args: str) -> dict[str, Any]:
        argv = [self.binary, "--json", *args]
        try:
            result = self.runner(
                argv, capture_output=True, text=True, check=False, shell=False,
                stdin=subprocess.DEVNULL, timeout=self.timeout_seconds, env=self._env(),
            )
        except subprocess.TimeoutExpired as exc:
            raise HerdrCoreError("HERDR_TIMEOUT") from exc
        except FileNotFoundError as exc:
            raise HerdrCoreError("HERDR_NOT_INSTALLED") from exc
        except OSError as exc:
            raise HerdrCoreError("HERDR_EXEC_FAILED", type(exc).__name__) from exc
        raw = result.stdout if result.returncode == 0 else result.stderr
        try:
            payload = json.loads(raw or "{}")
        except ValueError as exc:
            raise HerdrCoreError("HERDR_BAD_JSON") from exc
        if result.returncode != 0:
            error = payload.get("error") if isinstance(payload, dict) else None
            kind = str((error or {}).get("kind") or "cli_error").upper()
            # Do not echo upstream messages: they may contain command input or secrets.
            raise HerdrCoreError(f"HERDR_{kind}")
        if not isinstance(payload, dict):
            raise HerdrCoreError("HERDR_BAD_JSON")
        return payload

    @staticmethod
    def _info(item: dict[str, Any]) -> SessionInfo:
        address = str(item.get("address") or "")
        name = str(item.get("name") or address)
        foreground = item.get("foreground") or {}
        argv = foreground.get("argv") or item.get("argv") or []
        created_ms = int(item.get("created_ms") or 0)
        status_ms = int(item.get("status_ms") or created_ms)
        return SessionInfo(
            name=name, attached=False, windows=1,
            created_epoch=created_ms // 1000, activity_epoch=status_ms // 1000,
            pane_pid=int(item.get("pid") or 0),
            pane_current_command=str(argv[0] if argv else ""),
            pane_dead=item.get("state") != "live",
            session_id=f"herdr-core:{address}", pane_id=address,
            pane_in_mode=False,
            pane_current_path=str(foreground.get("cwd") or item.get("cwd") or ""),
        )

    def list_sessions(self) -> list[SessionInfo]:
        sessions: list[SessionInfo] = []
        for summary in self._call("ls").get("terminals", []):
            address = str(summary.get("address") or summary.get("name") or "")
            if not address:
                continue
            # hc ls intentionally emits a compact projection. Identity pins,
            # cwd, PID and OSC 7501 provenance require terminal.get facts.
            sessions.append(self._info(self._call("get", address)))
        return sessions

    def get_session(self, name: str) -> SessionInfo | None:
        try:
            return self._info(self._call("get", name))
        except HerdrCoreError as exc:
            if exc.code == "HERDR_NOT_FOUND":
                return None
            raise

    def capture_lines(self, session: str, lines: int, *, ansi: bool = False) -> list[str]:
        payload = self._call("read", "--lines", str(max(0, lines)), session)
        return str(payload.get("text") or "").rstrip("\n").splitlines()[-max(1, lines):]

    def send_text(self, session: str, text: str, press_enter: bool) -> None:
        if not press_enter:
            raise HerdrCoreError("UNSUPPORTED", "hc send always submits")
        self._call("send", session, text)

    def send_keys(self, session: str, keys: list[str]) -> None:
        self._call("keys", session, *[key.lower() for key in keys])

    def new_session(self, name: str, cwd: str, command: str | None = None, *,
                    show_on_desktop: bool = False,
                    extra_args: tuple[str, ...] = ()) -> tuple[bool, str | None]:
        argv = ["run", "--bg", "--name", name, "--cwd", cwd,
                "--label", "terminal-mcp=1", "--no-parent", "--outlive-parent"]
        if command:
            argv.extend((command, *extra_args))
        elif extra_args:
            raise HerdrCoreError("HERDR_INVALID_ARGUMENT", "extra_args require command")
        self._call(*argv)
        reason = "hc attach is available from a real terminal" if show_on_desktop else None
        return False, reason

    def detach_session(self, name: str) -> None:
        raise HerdrCoreError("UNSUPPORTED", "detach belongs to an attached client")

    def kill_session(self, name: str) -> None:
        self._call("kill", name)

    def exit_copy_mode(self, session: str) -> None:
        raise HerdrCoreError("UNSUPPORTED", "hc has no backend copy mode")

    def rename_session(self, old: str, new: str) -> None:
        raise HerdrCoreError("UNSUPPORTED", "hc names are immutable")

    def attach_command(self, name: str, *, observe: bool = False) -> list[str]:
        argv = [self.binary, "attach"]
        if observe:
            argv.append("--observe")
        return [*argv, name]

    def health(self) -> dict[str, Any]:
        try:
            status = self._call("server", "status")
            return {"backend": "herdr-core", "ok": True, "status": status}
        except HerdrCoreError as exc:
            return {"backend": "herdr-core", "ok": False, "error": exc.code}
